#!/usr/bin/env python3
"""Embed web/index.html (gzipped) into src/web/WebDisplayPage.h.
   python3 tools/embed_web.py          regenerate
   python3 tools/embed_web.py --check  fail if the header is out of sync with index.html
Output is deterministic (gzip mtime=0)."""
import gzip, re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
html = (root / "web" / "index.html").read_bytes()
out = root / "src" / "web" / "WebDisplayPage.h"
gz = gzip.compress(html, 9, mtime=0)

def render():
    rows = []
    for i in range(0, len(gz), 16):
        rows.append("  " + ",".join("0x%02x" % b for b in gz[i:i+16]))
    return ("#pragma once\n// GENERATED by tools/embed_web.py from web/index.html - do not edit.\n"
            "#include <Arduino.h>\n#include <pgmspace.h>\n"
            "static const size_t WEB_DISPLAY_PAGE_GZ_LEN = %d;\n"
            "static const uint8_t WEB_DISPLAY_PAGE_GZ[] PROGMEM = {\n%s\n};\n" % (len(gz), ",\n".join(rows)))

if "--check" in sys.argv:
    if not out.exists():
        sys.exit("missing " + str(out))
    txt = out.read_text()
    m = re.search(r"\{(.*)\};", txt, re.S)
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(1)))
    if gzip.decompress(data) != html:
        sys.exit("OUT OF SYNC: run python3 tools/embed_web.py")
    print("embedded page in sync (%d B raw, %d B gzip)" % (len(html), len(data)))
else:
    out.write_text(render())
    print("wrote %s (%d B raw -> %d B gzip)" % (out, len(html), len(gz)))
